   			<p>
   				Basava became the revolutionary who taught that right conduct is heaven. He declared that engaging in work itself is heaven and he taught the ideals of simple living and the equality between men and women. Thus Basava brought about reforms in all fields such as religion, morality, social life, economics, language and literature. No man or woman in the history of mankind has accomplished what Basava achieved within a few years. He is truly a great saint who preached to the people about humanity, honesty, simplicity, and the dignity of labour, equality among all human beings and human rights. The “Anubhava Mantapa” established by Basava in the 12th century laid the foundation of social democracy. He believed that a man becomes great not by his birth but by his conduct in society. He preached that everyone should continue in his professional work while leading a virtuous and spiritual life. He believed in the principle, “Kaayakave Kailasa” (Work is worship).

