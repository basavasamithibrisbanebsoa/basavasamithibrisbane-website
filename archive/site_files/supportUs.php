   <p>
 The organisation follows the concept that the human body itself is the temple or abode of God. The Basava philosophy

largely harps on the fact that "Service to man is service to God". By offering services to humanity one can not only improve the society but also 

inculcate social values which build a harmonious society.

Multidimensional reforms were introduced during the time of Saint Basava, which revitalise the contemporary society. Active missionary work is 

encouraged to be undertaken by each and every member of the society, through the concept of ‘Daasoha’, ‘kaayaka’, ‘jangama seva’ in other 

words by offering the holy feast, by carrying out holy deeds without expectation by serving the society to uplift moral values.

The organisation is built on these principles it does not seek any registration fee for the events or collect money towards the holy feast (prasada) 

or towards any entertainment programs.

The organisation is fortunate to have very kind members who whole-heartedly come forward to offer donations both in cash and kind out of their 

own will. As we are a not-for-profit organisation, our funds are largely dependent on our sponsors who willingly come forward to aid us towards this social cause.

