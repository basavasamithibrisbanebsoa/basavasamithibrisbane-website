				Tthere are two parts to this form of worship, “shiva pooja” and “shiva dhyana”, in other words, the first part involves worshipping of the shapeless, formless representation of the Supernatural Power and the second part is a unique form of meditation which aims to activate the inner senses to unite with God. 
